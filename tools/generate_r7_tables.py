from pathlib import Path
import math
p=Path(__file__).resolve().parent.parent
f=p/'src/r7_dsp_tables.h'
with f.open('w') as o:
 o.write('/* Generated by tools/generate_r7_tables.py. Immutable DSP coefficient cache. */\n#ifndef APO_R7_TABLES_H\n#define APO_R7_TABLES_H\n#define R7_PHASES 64\n#define R7_TAPS 48\n#define R7_BANDS 32\nstatic const float r7_sinc[R7_BANDS][R7_PHASES+1][R7_TAPS]={\n')
 for band in range(1,33):
  o.write('{\n'); cutoff=band/32
  for ph in range(65):
   vals=[]
   for j in range(48):
    x=j-23-ph/64
    w=.42+.5*math.cos(math.pi*x/24)+.08*math.cos(2*math.pi*x/24) if abs(x)<24 else 0
    vals.append(w*(cutoff if abs(x)<1e-15 else math.sin(math.pi*x*cutoff)/(math.pi*x)))
   total=sum(vals); o.write('{'+','.join(f'{v/total:.9e}f' for v in vals)+'},\n')
  o.write('},\n')
 o.write('};\nstatic const double r7_twiddle[1024][2]={\n')
 for k in range(1024):
  a=-2*math.pi*k/2048;o.write('{%.17g,%.17g},\n'%(math.cos(a),math.sin(a)))
 o.write('};\n#endif\n')
